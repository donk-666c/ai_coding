_BY_ID = {p["id"]: p for p in PERSONAS}
DEFAULT_PERSONA_ID = "gentle"
MAX_NAME_LENGTH = 12


def get_persona(persona_id: str | None) -> dict:
    """按 id 取人格，取不到就退回默认（前端传错不会导致失败）。"""
    return _BY_ID.get((persona_id or "").strip().lower(), _BY_ID[DEFAULT_PERSONA_ID])


def clean_name(raw: str | None, fallback: str) -> str:
    """清掉换行与控制字符，限长。空则用该人格的默认名字。"""
    name = " ".join(str(raw or "").split()).strip()
    name = "".join(ch for ch in name if ch.isprintable())
    if not name:
        return fallback
    return name[:MAX_NAME_LENGTH]


def build_system_prompt(persona_id: str | None, partner_name: str | None) -> tuple[str, str]:
    """组装最终 system prompt。

    返回 (prompt, 实际使用的名字)。{name} 用 replace 而不是 format，
    因为提示词里可能有其它花括号。
    """
    persona = get_persona(persona_id)
    name = clean_name(partner_name, persona["defaultName"])
    prompt = BASE_RULES.replace("{name}", name) + "\n" + persona["prompt"].replace("{name}", name)
    return prompt, name


